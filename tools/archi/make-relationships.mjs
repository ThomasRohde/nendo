// Writes tools/archi-relationships.mjs from archi-online's src/model/data/relations-matrix.ts (MIT),
// which archi-online generates from Archi's relationships.xml (ArchiMate 3.2). Run it from the
// repository root with archi-online checked out beside this repository:
//
//   node tools/archi/make-relationships.mjs [path-to-archi-online]
//
// The file keeps archi-online's shape, a source type to target type to relationship letters
// table, so a regeneration diffs line for line against the one before.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';

const repository = path.resolve(process.argv[2] ?? path.join(import.meta.dirname, '..', '..', '..', 'archi-online'));
const source = path.join(repository, 'src', 'model', 'data', 'relations-matrix.ts');
const text = await fs.readFile(source, 'utf8');
const body = text.slice(text.indexOf('= {') + 2).trim().replace(/;$/, '');
const matrix = Function(`"use strict"; return (${body});`)();
let commit = 'unknown';
try { commit = execFileSync('git', ['-C', repository, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }

const lines = [
  '// ArchiMate 3.2\'s relationship table: for each source type and target type, the letters of the',
  '// relationships allowed between them (a Access, c Composition, f Flow, g Aggregation, i Assignment,',
  '// n Influence, o Association, r Realization, s Specialization, t Triggering, v Serving). The type',
  '// Relationship stands for any relationship used as an end. Generated by tools/archi/make-relationships.mjs',
  `// from archi-online's src/model/data/relations-matrix.ts at commit ${commit} (MIT), which archi-online`,
  '// generates from Archi 5.9\'s relationships.xml. Regenerate rather than edit by hand.',
  '',
  'export const RELATIONSHIP_TABLE = Object.freeze({',
];
for (const from of Object.keys(matrix).sort()) {
  const row = Object.keys(matrix[from]).sort().map(to => `${to}: '${matrix[from][to]}'`).join(', ');
  lines.push(`  ${from}: { ${row} },`);
}
lines.push('});', '');
await fs.writeFile(path.join(import.meta.dirname, '..', 'archi-relationships.mjs'), lines.join('\n'), 'utf8');
console.log(`${Object.keys(matrix).length} source types from ${source} at ${commit}`);
