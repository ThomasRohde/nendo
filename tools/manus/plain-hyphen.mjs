// Writes extensions/manuscript/hyphenation.mjs from plain TeX's hyphen.tex: the patterns
// LaTeX's default English loads, which the paper's LaTeX reference hyphenates with, so the
// preview breaks a word where TeX does. hyph-utf8's en-us (ushyphmax) is a different set.
//   node tools/manus/plain-hyphen.mjs <path to hyphen.tex from any TeX distribution>
import fs from 'node:fs';
import path from 'node:path';
const source = process.argv[2];
if (!source) throw Error('Name hyphen.tex: node tools/manus/plain-hyphen.mjs <path>');
const tex = fs.readFileSync(source, 'utf8').replace(/\r\n/g, '\n');
const block = name => {
  const start = tex.indexOf(`\\${name}{`);
  if (start < 0) throw Error(`No \\${name} in ${source}`);
  return tex.slice(start + name.length + 2, tex.indexOf('}', start)).replace(/%.*$/gm, '').split(/\s+/).filter(Boolean);
};
const patterns = block('patterns'), exceptions = block('hyphenation');
if (patterns.length < 4000) throw Error(`Only ${patterns.length} patterns in ${source}`);
const header = tex.split('\n').filter(line => line.startsWith('%')).slice(0, 4).map(line => `//${line.slice(1)}`).join('\n');
const out = `// Plain TeX's English hyphenation, generated by tools/manus/plain-hyphen.mjs from hyphen.tex:
// Liang's patterns and Knuth's exceptions, as LaTeX's default English hyphenates. The source
// file's terms, which this converted copy keeps under another name:
${header}

const PATTERNS = ${JSON.stringify(patterns.join(' '))};
const EXCEPTIONS = ${JSON.stringify(exceptions.join(' '))};

let table = null;
function load() {
  table = { patterns: new Map(), exceptions: new Map(), longest: 0 };
  for (const pattern of PATTERNS.split(' ')) {
    const letters = pattern.replace(/\\d/g, ''), values = [];
    let value = 0;
    for (const c of pattern) { if (c >= '0' && c <= '9') value = Number(c); else { values.push(value); value = 0; } }
    values.push(value);
    table.patterns.set(letters, values);
    table.longest = Math.max(table.longest, letters.length);
  }
  for (const word of EXCEPTIONS.split(' ')) table.exceptions.set(word.replace(/-/g, ''), word);
}

/**
 * \`word\` with \`hyphenChar\` wherever TeX's patterns allow a break: the odd values Liang's
 * patterns leave between its letters, or the places its exception lists. The minimums of letters
 * before and after a break are the caller's.
 */
export function hyphenate(word, { hyphenChar = '\\u00ad' } = {}) {
  if (!table) load();
  const lower = word.toLowerCase();
  const exception = table.exceptions.get(lower);
  if (exception) {
    let out = '', at = 0;
    for (const c of exception) out += c === '-' ? hyphenChar : word[at++];
    return out;
  }
  const dotted = \`.\${lower}.\`, points = new Array(dotted.length + 1).fill(0);
  for (let i = 0; i < dotted.length; i++) {
    for (let j = i + 1; j <= Math.min(dotted.length, i + table.longest); j++) {
      const values = table.patterns.get(dotted.slice(i, j));
      if (values) values.forEach((v, k) => { if (v > points[i + k]) points[i + k] = v; });
    }
  }
  let out = '';
  for (let i = 0; i < word.length; i++) out += (i > 0 && points[i + 1] % 2 ? hyphenChar : '') + word[i];
  return out;
}
`;
const target = path.resolve(import.meta.dirname, '../../extensions/manuscript/hyphenation.mjs');
fs.writeFileSync(target, out);
console.log(`${target}: ${patterns.length} patterns, ${exceptions.length} exceptions, ${Buffer.byteLength(out)} bytes`);
